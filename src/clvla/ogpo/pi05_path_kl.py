"""Teacher-student stochastic path KL on a STUDENT-generated chain of the frozen Task 6 `ogpo_discrete` sampler (real pi0.5).
EVALUATION ONLY: every output is gradient-stopped. This is not a training loss; the KL-gradient estimator is a separate task.

Frozen configuration (tests/ogpo_port/README.md): K = 10, s_k = 1 - k/K, Delta = 1/K, sigma = 0.05, sigma_k = sigma sqrt(s_k),
score correction ON, all 320 latent coordinates stochastic, no clipping, no normalisation. For X^S = (x_0, ..., x_K) ~ p_S(X|o),
both policies are evaluated at the SAME student states (the teacher never rolls out its own states):

    v_j,k  = v_j(x_k, s_k, o),   mu_j,k = x_k - Delta [(1 + sigma^2 (1 - s_k)/2) v_j,k + sigma^2/2 x_k],   j in {S, T}
    mu_S,k - mu_T,k = -Delta (1 + sigma^2 (1 - s_k)/2) (v_S,k - v_T,k)        (x_k shared, its terms cancel)

    D_KL,k = ||mu_S,k - mu_T,k||^2 / (2 sigma_k^2)                                      (1) direct Gaussian form
           = Delta^2 (1 + sigma^2 (1 - s_k)/2)^2 / (2 sigma^2 s_k) ||v_S,k - v_T,k||^2  (2) weighted velocity form = w_k ||dv||^2
    K(X, o) = sum_{k=0}^{K-1} D_KL,k;   path KL = E_{X ~ p_S}[K(X, o)] = E_{X ~ p_S}[R(X, o)],
    R(X, o) = log p_S(X|o) - log p_T(X|o)   (the shared N(0, I) initial density cancels).

(1) uses the means recomputed by the frozen Task 7 `path_log_prob` (which also gives log p_S, log p_T and R); (2) uses velocities
from the frozen Task 5 `velocity` adapter. The two are computed independently and are meant to be compared numerically.
The observation enters through the two prefix caches; they must hold identical preprocessed observations and the chain's
batch shape (bf16 velocities depend on GEMM shapes: Task 5 caveat). bf16 model, fp32 latent states and KL quantities.
"""

from __future__ import annotations

from typing import Any

import numpy as np

from clvla.ogpo import pi05_path_logprob as plp
from clvla.ogpo import pi05_sde as sde
from clvla.ogpo import pi05_velocity as pv

# Diagnostic coordinate groups of the (10, 32) chunk: they add up exactly to the full conditional KL (shared diagonal covariance).
GROUPS = {"executed": (slice(0, 5), slice(0, 7)), "unexecuted": (slice(5, 10), slice(0, 7)), "padded": (slice(0, 10), slice(7, 32))}


def kl_coefficients(cfg: "sde.SDEConfig" = sde.SDEConfig()) -> dict:
    """float64 per-step coefficients: coef_k = Delta (1 + sigma^2 (1 - s_k)/2) (mean-difference scale), w_k = coef_k^2 / (2 sigma_k^2)."""
    delta = 1.0 / cfg.num_steps
    s, sd = np.asarray(cfg.times(), np.float64), np.asarray(cfg.stds(), np.float64)
    coef = delta * (1.0 + 0.5 * cfg.sigma**2 * (1.0 - s))
    return {"times": s, "stds": sd, "coef": coef, "weights": coef**2 / (2.0 * sd**2)}


def _check_inputs(teacher_cache, student_cache, chain, cfg):
    import jax

    if cfg.noise_mode != sde.NOISE_MODE or not cfg.score_correction or cfg.sigma <= 0:
        raise ValueError("path_kl implements exactly the frozen ogpo_discrete sampler with score correction and sigma > 0")
    b = chain.shape[0]
    for name, c in (("teacher", teacher_cache), ("student", student_cache)):
        if c.prefix_mask.shape[0] != b:
            raise ValueError(f"{name} prefix cache batch {c.prefix_mask.shape[0]} != chain batch {b} (use matching batch shapes)")
    if teacher_cache.observation is not student_cache.observation:
        ta, sa = jax.tree.leaves(teacher_cache.observation), jax.tree.leaves(student_cache.observation)
        if len(ta) != len(sa) or not all(np.array_equal(np.asarray(x), np.asarray(y)) for x, y in zip(ta, sa)):
            raise ValueError("teacher and student prefix caches must be built from the same observation")


def path_kl(teacher: Any, teacher_cache: "pv.PrefixCache", student: Any, student_cache: "pv.PrefixCache", chain: Any,
            cfg: "sde.SDEConfig" = sde.SDEConfig()) -> dict:
    """chain: (B, K+1, 10, 32) generated by the STUDENT (frozen Task 6 sampler). Returns gradient-stopped fp32 arrays:
      kl_direct, kl_velocity (B, K)        per-step conditional KL, forms (1) and (2)
      path_kl_direct, path_kl_velocity (B,) per-trajectory conditional-KL sums K(X, o)
      kl_groups (B, K, 3)                  form (2) split into executed / unexecuted / padded coordinates (GROUPS order)
      log_ratio (B,)                       R = log p_S - log p_T (Task 7 totals);  log_ratio_transitions (B, K);  initial_diff (B,)
      logprob_student, logprob_teacher     the Task 7 path_log_prob outputs (total, initial, transitions, means, stds)
      means_student, means_teacher (B, K, 10, 32), velocities_student, velocities_teacher (B, K, 10, 32)
      dv_sq (B, K) = ||v_S - v_T||^2,  dmu_sq (B, K) = ||mu_S - mu_T||^2,  coef (K,), weights (K,), stds (K,), times (K,)
    """
    import jax
    import jax.numpy as jnp

    chain = jax.lax.stop_gradient(jnp.asarray(chain, jnp.float32))
    _check_inputs(teacher_cache, student_cache, chain, cfg)
    co = kl_coefficients(cfg)
    lp_s = plp.path_log_prob(student, student_cache, chain, cfg)            # FROZEN Task 7: means recomputed at student states
    lp_t = plp.path_log_prob(teacher, teacher_cache, chain, cfg)            # teacher scores the SAME student states
    dmu = lp_s["means"] - lp_t["means"]
    dmu_sq = jnp.sum(dmu**2, axis=(2, 3))
    kl_direct = dmu_sq / (2.0 * jnp.asarray(co["stds"], jnp.float32) ** 2)
    vs, vt = [], []
    for k, s in enumerate(cfg.times()):
        vs.append(pv.velocity(student, student_cache, chain[:, k], s))     # FROZEN Task 5 adapter
        vt.append(pv.velocity(teacher, teacher_cache, chain[:, k], s))
    vs, vt = jnp.stack(vs, axis=1), jnp.stack(vt, axis=1)
    w = jnp.asarray(co["weights"], jnp.float32)
    dv2 = (vs - vt) ** 2
    dv_sq = jnp.sum(dv2, axis=(2, 3))
    kl_velocity = w * dv_sq
    groups = jnp.stack([w * jnp.sum(dv2[:, :, r, c], axis=(2, 3)) for r, c in GROUPS.values()], axis=-1)
    out = {"kl_direct": kl_direct, "kl_velocity": kl_velocity, "path_kl_direct": jnp.sum(kl_direct, axis=1),
           "path_kl_velocity": jnp.sum(kl_velocity, axis=1), "kl_groups": groups,
           "log_ratio": lp_s["total"] - lp_t["total"], "log_ratio_transitions": lp_s["transitions"] - lp_t["transitions"],
           "initial_diff": lp_s["initial"] - lp_t["initial"], "logprob_student": lp_s, "logprob_teacher": lp_t,
           "means_student": lp_s["means"], "means_teacher": lp_t["means"], "velocities_student": vs, "velocities_teacher": vt,
           "dv_sq": dv_sq, "dmu_sq": dmu_sq, "coef": jnp.asarray(co["coef"], jnp.float32), "weights": w,
           "stds": jnp.asarray(co["stds"], jnp.float32), "times": jnp.asarray(co["times"], jnp.float32)}
    return jax.tree.map(jax.lax.stop_gradient, out)                          # evaluation only: never a training gradient
