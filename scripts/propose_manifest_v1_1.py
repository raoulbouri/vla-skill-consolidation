"""Build the task manifest v1.1 CANDIDATE from real R8 screening results; never touches the frozen v1.0 manifest.

  scripts/py-sim scripts/propose_manifest_v1_1.py --screening outputs/screening/<run>       # report + candidate
  scripts/py-sim scripts/propose_manifest_v1_1.py --screening <run> --allow-category-change  # if no container passes R8
  scripts/py-sim scripts/propose_manifest_v1_1.py --freeze --reviewed-by "<name>"            # after review only

Writes configs/proposed/task_manifest_v1.1.candidate.yaml (frozen: false; runners refuse it). --freeze copies it to
configs/task_manifest_v1.1.yaml with frozen: true and manifest_version 1.1.0. Both refuse to overwrite.
Requires real candidate results: tasks without screening are reported as "needs screening", never guessed.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

import yaml

from clvla.selection_v11 import candidate_manifest, missing_or_failed_audit, propose_replacement, screening_table
from clvla.tasks import manifest_content_sha256, parse_manifest

ROOT = Path(__file__).resolve().parents[1]
CANDIDATE = ROOT / "configs/proposed/task_manifest_v1.1.candidate.yaml"
FROZEN = ROOT / "configs/task_manifest_v1.1.yaml"


def v10_rules():
    """category() and jaccard() exactly as used to build manifest v1.0 (imported from the unmodified script)."""
    spec = importlib.util.spec_from_file_location("clvla_build_manifest_v10", str(ROOT / "scripts/build_task_manifest.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.category, mod.jaccard


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--screening", help="outputs/screening/<run> directory (summary.json + screening_metadata.json)")
    ap.add_argument("--config", default=str(ROOT / "configs/proposed/screening_v1.1.yaml"))
    ap.add_argument("--allow-category-change", action="store_true")
    ap.add_argument("--freeze", action="store_true")
    ap.add_argument("--reviewed-by", default=None)
    args = ap.parse_args(argv)

    if args.freeze:
        if not args.reviewed_by:
            raise SystemExit("--freeze requires --reviewed-by")
        if FROZEN.exists():
            raise SystemExit(f"{FROZEN} exists; frozen manifests are never overwritten")
        cand = yaml.safe_load(CANDIDATE.read_text())
        if cand["content_sha256"] != manifest_content_sha256(cand):
            raise SystemExit("candidate was edited after generation (checksum mismatch); regenerate it")
        cand.update({"manifest_version": "1.1.0", "frozen": True, "status": f"frozen; reviewed by {args.reviewed_by}"})
        cand["content_sha256"] = manifest_content_sha256(cand)
        parse_manifest(cand, str(FROZEN))
        FROZEN.write_text("# FROZEN task manifest v1.1 (generated by scripts/propose_manifest_v1_1.py --freeze).\n"
                          + yaml.safe_dump(cand, sort_keys=False, width=120))
        print(f"frozen: {FROZEN} ({cand['content_sha256']})")
        return 0

    if not args.screening:
        raise SystemExit("--screening <outputs/screening/run> is required (real results; nothing is guessed)")
    scfg = yaml.safe_load(Path(args.config).read_text())
    run = Path(args.screening)
    summary = json.loads((run / "summary.json").read_text())
    table = screening_table(summary["per_task"], list(range(scfg["init_states"]["start"], scfg["init_states"]["stop"])),
                            summary["init_states"])
    v10 = yaml.safe_load((ROOT / "configs/task_manifest.yaml").read_text())
    parse_manifest(v10, "configs/task_manifest.yaml")  # must still be the intact frozen v1.0
    snapshot = json.loads((ROOT / "configs/libero90_tasks.json").read_text())
    category, jaccard = v10_rules()
    proposal = propose_replacement(v10, snapshot, table, control=scfg["control_tasks"][0], r8_max=scfg["r8_max_successes"],
                                   category_fn=category, jaccard_fn=jaccard,
                                   allow_category_change=args.allow_category_change,
                                   candidate_indices=scfg["replacement_candidates"])
    print("candidates:")
    for e in proposal["considered"]:
        print(f"  t{e['libero_90_index']:02d} {e['category']:<16} screening={e['screening']} R8={e['r8']:<10} "
              f"J={e['nearest_pretrain_jaccard']}  {'ELIGIBLE' if not e['rejected_because'] else e['rejected_because']}")
    flagged = missing_or_failed_audit(proposal)
    print(f"retained-task R8 audit: {proposal['retained_r8_audit']}")
    if flagged:
        print(f"WARNING: retained tasks not passing R8 (decision needed, nothing changed): {flagged}")
    if proposal["needs_screening"]:
        print(f"needs screening before a decision: {proposal['needs_screening']}")
    if proposal["replacement"] is None:
        print("NO replacement satisfies R1-R8 under the current options; no candidate written.")
        return 1
    rep = proposal["replacement"]
    row = {"libero_90_index": rep["libero_90_index"], "name": rep["name"], "instruction": rep["instruction"],
           "scene": rep["scene"], "category": rep["category"]}
    snap_row = {r["idx"]: r for r in snapshot["libero_90"]}[rep["libero_90_index"]]
    lock = json.loads((ROOT / "configs/dataset.lock.json").read_text())
    demo = f"libero_90/{rep['name']}_demo.hdf5"
    row.update({"bddl_file": f"{snap_row['problem_folder']}/{snap_row['bddl_file']}",
                "init_states_file": f"{snap_row['problem_folder']}/{snap_row['init_states_file']}",
                "num_init_states": snap_row["num_init_states"], "demo_file": demo,
                "demo_sha256": lock["files"][demo]["sha256"], "demo_size_bytes": lock["files"][demo]["size"],
                "overlap": {"nearest_pretrain_suite": rep["nearest_pretrain_suite"],
                            "nearest_pretrain_instruction": rep["nearest_pretrain_instruction"],
                            "nearest_pretrain_jaccard": rep["nearest_pretrain_jaccard"]},
                "r8_screening": rep["screening"]})
    cand = candidate_manifest(v10, proposal, row, screening_ref=str(run), r8_max=scfg["r8_max_successes"],
                              allow_category_change=args.allow_category_change)
    if CANDIDATE.exists():
        raise SystemExit(f"{CANDIDATE} exists; move it aside deliberately before regenerating")
    CANDIDATE.parent.mkdir(parents=True, exist_ok=True)
    CANDIDATE.write_text("# CANDIDATE task manifest v1.1 (NOT frozen; runners refuse it). Review before --freeze.\n"
                         + yaml.safe_dump(cand, sort_keys=False, width=120))
    print(f"candidate: {CANDIDATE}; replacement t{rep['libero_90_index']} at position {proposal['removed']['position']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
